
void main() {
  // 1. Direct type
  String name = "Mahmoud";
  int age = 31;
  print(name);
  print(age);

  // 2. var
  var city = "Cairo";
  var score = 100;
  print(city);
  print(score);

  // 3. dynamic
  dynamic message = "Hello";
  message = 25;
  message = true;
  print(message);

  // 4. final
  final country = "Egypt";
  print(country);

  // 5. const
  const pi = 3.14;
  const area = pi * 12 * 12;
  print(area);
}
