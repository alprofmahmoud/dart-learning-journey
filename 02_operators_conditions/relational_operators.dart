void main(){
  int a = 10;
  int b = 20;

  // Greater than
  print(a > b); // false

  // Less than
  print(a < b); // true

  // Greater than or equal
  print(a >= b);  // false

  // less than or equal
  print(a <= b);  // true

  // Equal
  print(a == b);  // false

  // Not Equal
  print(a != b);  // true
}
